/**
 * Build the briefing digest (subject + body) from analysis hits.
 */

function formatDate(date) {
  const day = String(date.getDate()).padStart(2, '0');
  const month = date.toLocaleString('default', { month: 'short' });
  const year = date.getFullYear();
  return `${day}-${month}-${year}`;
}

function buildDigest({ municipality, meetingTitle, meetingDate, sourceUrl, hits, generatedAt = new Date() }) {
  const dateStr = formatDate(new Date(meetingDate));
  const subject = `🏛️ Council Watchdog: ${municipality} — ${meetingTitle || 'Meeting'}`;

  let body = `Automated BNS Civic Vigilance Briefing\n\n`;
  body += `Municipality: ${municipality}\n`;
  body += `Meeting: ${meetingTitle || 'Regular Council Meeting'}\n`;
  body += `Meeting Date: ${dateStr}\n`;
  body += `Source: ${sourceUrl}\n\n`;

  body += `### 🟡 Items of Interest (Housing & Transportation)\n`;

  if (!hits || hits.length === 0) {
    body += 'No specific keywords found (Housing, Transport, etc.). Review manually if needed.\n';
  } else {
    hits.forEach((h) => {
      body += `**${h.keyword}** detected:\n`;
      h.snippets.forEach((s) => {
        body += `  - "...${s.replace(/\s+/g, ' ').trim()}..."\n`;
      });
      body += '\n';
    });
  }

  body += `\n(Generated by council-watchdog on ${formatDate(generatedAt)})\n`;

  return { subject, body };
}

module.exports = { buildDigest, formatDate };